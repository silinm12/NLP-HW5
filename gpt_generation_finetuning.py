import sys
import os
import torch
from datasets import load_from_disk, load_dataset
from transformers import GPT2LMHeadModel, GPT2Tokenizer, Trainer,TrainingArguments
from transformers import TrainingArguments
from transformers import DataCollatorForLanguageModeling

def load_data(path_to_subset):
    # Requirement from Part A
    if os.path.exists(path_to_subset):
        print(f"Loading data from disk: {path_to_subset}")
        return load_from_disk(path_to_subset)
    else:
        print("Data not found on disk. Downloading and creating subset...")
        dataset = load_dataset("imdb")
        # Ensure you use the exact same seed/range as instructed in Part A
        subset = dataset["train"].shuffle(seed=42).select(range(500))
        subset.save_to_disk(path_to_subset)
        return subset

#part C
#3.2
def tokenize_reviews(dataset,tokenizer, max_length=150):
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token

    def tokenize_function(examples):
        return tokenizer(examples['text'], padding="max_length", truncation=True, max_length=max_length)

    tokenized_dataset = dataset.map(tokenize_function, batched=True)
    tokenized_dataset = tokenized_dataset.rename_column("label", "labels")
    return tokenized_dataset

#3.3& 3.4
def fine_tune(train_data,save_dir, model_name_suffix):
    # 3.1
    model = GPT2LMHeadModel.from_pretrained("gpt2")
    tokenizer = GPT2Tokenizer.from_pretrained("gpt2")

    # 3.2
    tokenized_dataset = tokenize_reviews(train_data, tokenizer)

    #3.3
    training_args = TrainingArguments(
        output_dir=os.path.join(save_dir, f"checkpoints_{model_name_suffix}"),
        overwrite_output_dir=True,
        num_train_epochs=3,
        per_device_train_batch_size=4,
        save_strategy="no",
        eval_strategy="no",  # No evaluation set required by instructions for this part
        learning_rate=5e-5,
        use_cpu=False if device_check() == "cuda" else True,
        logging_steps=10
    )
    #3.4
    trainer = Trainer(model=model, args=training_args,train_dataset=tokenized_dataset,data_collator=DataCollatorForLanguageModeling(tokenizer=tokenizer,mlm=False))
    #3.5
    trainer.train()
    #3.6
    final_path = os.path.join(save_dir, f"gpt2_{model_name_suffix}")
    trainer.model.save_pretrained(final_path)
    tokenizer.save_pretrained(final_path)
    #3.7- verification
    model = GPT2LMHeadModel.from_pretrained(final_path)
    tokenizer = GPT2Tokenizer.from_pretrained(final_path)
    #padding token
    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    #3.8 prepare prompt
    prompt="The movie was"
    input_ids = tokenizer.encode(prompt, return_tensors="pt")
    attention_mask = input_ids.ne(tokenizer.pad_token_id)

    #3.9 & 3.10
    generated_reviews = []
    input_ids = input_ids.to(model.device)
    attention_mask = attention_mask.to(model.device)
    for i in range(10):
        with torch.no_grad():
            output = model.generate(
                input_ids,
                attention_mask=attention_mask,
                max_length=50,  # Keep short for speed
                temperature=1.0,
                top_k=50,
                top_p=0.95,
                repetition_penalty=1.2,
                do_sample=True,
                num_return_sequences=1,
            )
        generated_text = tokenizer.decode(output[0], skip_special_tokens=True)
        generated_reviews.append(generated_text.replace("\n", " ").strip())

    return generated_reviews

