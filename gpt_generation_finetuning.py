    pos_data= dataset.filter(lambda x: x['label']==1).select(range(100))
    neg_data= dataset.filter(lambda x: x['label']==0).select(range(100))

    #train both models
    pos_reviews = fine_tune(pos_data, save_dir, "positive")
    neg_reviews = fine_tune(neg_data, save_dir, "negative")

